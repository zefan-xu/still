const TRAY = walls(box(-19, 19, -25, 25), 2.4);
const TRAY_TOP = 11;
const NOTCH = { x: 5.5, z: 6.4 };
const REST_Z = FLOOR + STACK_TURNS.length * PRINT_H;

const CHUTE = walls(box(-17.2, 17.2, -23.2, 23.2), 1.4);
const LIP = walls(box(-17.2, 17.2, -23.2, 23.2), 2.6);
const CHUTE_Z = 31;
const CHUTE_TOP = 39;
const LIP_H = 1.2;
const START_Z = 32.6;

const POST = { x: -28.2, y: -34.2, w: 4.4, d: 4.4, r: 0.8 };
const ARM_H = 2.4;
const ARM_Z = CHUTE_TOP + LIP_H - ARM_H;
const COLLAR_Z = ARM_Z - 0.8;
const COLLAR_H = ARM_H + 1.6;
const POST_TOP = COLLAR_Z + COLLAR_H + 3;

const figPoints = [...k.boxCorners(PLINTH, -FOOT_H, FLOOR), ...k.boxCorners(LIP.outer, CHUTE_TOP, CHUTE_TOP + LIP_H), ...k.boxCorners(k.insetPlan(POST, -0.6), POST_TOP, POST_TOP + 1.2)];
