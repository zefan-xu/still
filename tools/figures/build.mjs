const BEGIN = "<!-- Figure tones: generated by tools/figures/build.mjs -->";
const END = "<!-- End of figure tones -->";
function withTones(styles, style, tones) {
  const open = styles.indexOf(`<style name="${style}"`);
  const close = styles.indexOf("</style>", open);
  if (open < 0 || close < 0) throw new Error(`styles.xml has no ${style}`);
  const block = [BEGIN, ...Object.entries(ATTRS).map(([tone, name]) => `<item name="${name}">${tones[tone]}</item>`), END].map((line) => `        ${line}`).join("\n");
  const section = styles.slice(open, close);
  const start = section.indexOf(BEGIN);
  const next = start < 0 ? `${section.trimEnd()}\n${block}\n    ` : `${section.slice(0, start).trimEnd()}\n${block}\n${section.slice(section.indexOf(END) + END.length).replace(/^\s*\n/, "")}`;
  return styles.slice(0, open) + next + styles.slice(close);
}
const STYLES = join(RES, "values", "styles.xml");
