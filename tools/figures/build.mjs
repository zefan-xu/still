// "#AARRGGBB" or "#RRGGBB" to an SVG colour plus opacity.
function svgColour(hex) {
  if (hex.length === 9) return [`#${hex.slice(3)}`, parseInt(hex.slice(1, 3), 16) / 255];
  return [hex, 1];
}

let gradientId = 0;
function svgOps(art, tones, transform = "") {
  const out = [];
  for (const op of merged(art.ops)) {
    if (op.kind === "halo") {
      const id = `halo${gradientId++}`;
      const [colour, opacity] = svgColour(tones[op.tone]);
      out.push(
        `<defs><radialGradient id="${id}"><stop offset="0" stop-color="${colour}" stop-opacity="${num(opacity)}"/><stop offset="0.45" stop-color="${colour}" stop-opacity="${num(opacity)}"/><stop offset="1" stop-color="#000" stop-opacity="0"/></radialGradient></defs>`,
        `<ellipse cx="${num(op.cx)}" cy="${num(op.cy)}" rx="${num(op.rx)}" ry="${num(op.ry)}" fill="url(#${id})"/>`,
      );
      continue;
    }
    const [colour, opacity] = svgColour(tones[op.tone] ?? op.tone);
    const alpha = num(opacity * op.alpha);
    if (op.kind === "fill") {
      out.push(`<path d="${op.d}" fill="${colour}"${alpha !== "1" ? ` fill-opacity="${alpha}"` : ""}${op.evenOdd ? ` fill-rule="evenodd"` : ""}/>`);
    } else {
      out.push(`<path d="${op.d}" fill="none" stroke="${colour}" stroke-width="${num(op.width)}" stroke-linecap="round" stroke-linejoin="round"${alpha !== "1" ? ` stroke-opacity="${alpha}"` : ""}/>`);
    }
  }
  return transform ? `<g transform="${transform}">${out.join("")}</g>` : out.join("");
}

