const num = (value) => {
  const text = String(Math.round(value * 100) / 100);
  return text === "-0" ? "0" : text;
};
const circleD = (x, y, r) => `M${num(x - r)} ${num(y)}a${num(r)} ${num(r)} 0 1 0 ${num(2 * r)} 0a${num(r)} ${num(r)} 0 1 0 ${num(-2 * r)} 0Z`;

class Art {
  constructor(lines) {
    this.ops = [];
    this.lines = lines;
  }
  fill(d, tone, { alpha = 1, evenOdd = false } = {}) {
    if (d) this.ops.push({ kind: "fill", d, tone, alpha, evenOdd });
  }
  stroke(d, tone, width = this.lines.line, { alpha = 1 } = {}) {
    if (d) this.ops.push({ kind: "stroke", d, tone, width, alpha });
  }
  halo(cx, cy, rx, ry) {
    this.ops.push({ kind: "halo", cx, cy, rx, ry, tone: "halo" });
  }
  dots(points, r, tone, alpha = 1) {
    this.fill(points.map(([x, y]) => circleD(x, y, r)).join(""), tone, { alpha });
  }
  // Mirrors k.solidSvg: paper hull, four side shades, lighter top, crease, bevel, inner lines, outline.
  solid(paths, { tone = "hi", crease = "faint", flat = false, inner } = {}) {
    this.fill(paths.fill, "paper");
    if (!flat) {
      paths.shades.forEach((d, shade) => this.fill(d, `shade${shade}`));
      this.fill(paths.top, "top");
    }
    if (crease !== "none") {
      this.stroke(paths.crease, crease);
      this.stroke(paths.bevel, crease);
    }
    if (inner) inner(this);
    this.stroke(paths.outline, tone, this.lines.edge);
  }
}

// Consecutive strokes with the same paint are merged into one path; fills never are, because
// joined sub-paths of opposite winding would punch holes under the non-zero rule.
function merged(ops) {
  const out = [];
  for (const op of ops) {
    const last = out[out.length - 1];
    if (last && op.kind === "stroke" && last.kind === "stroke" && last.tone === op.tone && last.width === op.width && last.alpha === 1 && op.alpha === 1) {
      out[out.length - 1] = { ...last, d: last.d + op.d };
    } else out.push(op);
  }
  return out;
}

// sections: [{ art, paint, group }], drawn in order; `group` is optional transform attributes.
function vectorXml(sections, { width, height, viewport }) {
  const [vw, vh] = viewport;
  const body = sections.flatMap(({ art, paint, group }) => {
    const lines = opsXml(art, paint, "    ".repeat(group ? 2 : 1));
    return group ? [`    <group ${group}>`, ...lines, `    </group>`] : lines;
  });
  const usesAapt = sections.some(({ art }) => art.ops.some((op) => op.kind === "halo"));
  return [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- ${GENERATED} -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"${usesAapt ? `\n    xmlns:aapt="http://schemas.android.com/aapt"` : ""}`,
    `    android:width="${width}dp" android:height="${height}dp"`,
    `    android:viewportWidth="${num(vw)}" android:viewportHeight="${num(vh)}">`,
    ...body,
    `</vector>`,
    ``,
  ].join("\n");
}

function opsXml(art, paint, indent) {
  return merged(art.ops).map((op) => {
    if (op.kind === "halo") {
      const { cx, cy, rx, ry } = op;
      return [
        `${indent}<group android:pivotX="${num(cx)}" android:pivotY="${num(cy)}" android:scaleY="${num(ry / rx)}">`,
        `${indent}    <path android:pathData="${circleD(cx, cy, rx)}">`,
        `${indent}        <aapt:attr name="android:fillColor">`,
        `${indent}            <gradient android:type="radial" android:centerX="${num(cx)}" android:centerY="${num(cy)}" android:gradientRadius="${num(rx)}">`,
        `${indent}                <item android:offset="0" android:color="${paint(op.tone)}" />`,
        `${indent}                <item android:offset="0.45" android:color="${paint(op.tone)}" />`,
        `${indent}                <item android:offset="1" android:color="#00000000" />`,
        `${indent}            </gradient>`,
        `${indent}        </aapt:attr>`,
        `${indent}    </path>`,
        `${indent}</group>`,
      ].join("\n");
    }
    const attrs = [];
    if (op.kind === "fill") {
      attrs.push(`android:fillColor="${paint(op.tone)}"`);
      if (op.alpha !== 1) attrs.push(`android:fillAlpha="${num(op.alpha)}"`);
      if (op.evenOdd) attrs.push(`android:fillType="evenOdd"`);
    } else {
      attrs.push(`android:strokeColor="${paint(op.tone)}"`, `android:strokeWidth="${num(op.width)}"`, `android:strokeLineCap="round"`, `android:strokeLineJoin="round"`);
      if (op.alpha !== 1) attrs.push(`android:strokeAlpha="${num(op.alpha)}"`);
    }
    attrs.push(`android:pathData="${op.d}"`);
    return `${indent}<path ${attrs.join(" ")} />`;
  });
}

const attrPaint = (tone) => `?attr/${ATTRS[tone]}`;
