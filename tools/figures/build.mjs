// Shared geometry helpers.

const byDepth = (P) => (points) => [...points].sort((a, b) => k.depthOf([a[0], a[1], 0], P) - k.depthOf([b[0], b[1], 0], P));
const box = (x0, x1, y0, y1, r = 0) => ({ x: x0, y: y0, w: x1 - x0, d: y1 - y0, r });
const turned = (ring, degrees, [ox, oy] = [0, 0]) => {
  const a = (degrees * Math.PI) / 180;
  const [c, s] = [Math.cos(a), Math.sin(a)];
  return ring.map(([x, y]) => [x * c - y * s + ox, x * s + y * c + oy]);
};
function fitted(points, width, pad, options = {}) {
  const flat = points.map((point) => k.iso(point, { origin: [0, 0], scale: 1, ...options }));
  const xs = flat.map(([x]) => x);
  const ys = flat.map(([, y]) => y);
  const aspect = (Math.max(...ys) - Math.min(...ys)) / (Math.max(...xs) - Math.min(...xs));
  const height = Math.ceil((width - pad * 2) * aspect + pad * 2);
  return { P: k.fitProjection(points, width, height, { pad, ...options }), height };
}
// A vector can't blur, so the halo is a radial gradient squashed into an ellipse. `within` keeps
// it inside the viewport width, where a drawable would cut it off.
function haloUnder(art, plan, z, P, { grow = 1.08, drop = 2, within = Infinity } = {}) {
  const flat = k.boxCorners(plan, z, z).map((point) => k.iso(point, P));
  const xs = flat.map(([x]) => x);
  const ys = flat.map(([, y]) => y);
  const cx = (Math.max(...xs) + Math.min(...xs)) / 2;
  const [rx, ry] = [((Math.max(...xs) - Math.min(...xs)) / 2) * grow, ((Math.max(...ys) - Math.min(...ys)) / 2) * grow];
  const fit = Math.min(1, cx / rx, (within - cx) / rx);
  art.halo(cx, (Math.max(...ys) + Math.min(...ys)) / 2 + drop, rx * fit, ry * fit);
}
// A rectangular wall round `inner`, split into the far L (-x and -y sides) and the near L
// (+x and +y sides). For any azimuth between 0 and 90 degrees the far L is behind everything
// inside the wall and the near L is in front of it, whatever the height.
function walls(inner, thickness) {
  const [ix0, iy0, ix1, iy1] = [inner.x, inner.y, inner.x + inner.w, inner.y + inner.d];
  const [ox0, oy0, ox1, oy1] = [ix0 - thickness, iy0 - thickness, ix1 + thickness, iy1 + thickness];
  return {
    outer: { x: ox0, y: oy0, w: ox1 - ox0, d: oy1 - oy0 },
    far: [[ox0, oy0], [ix1, oy0], [ix1, iy0], [ix0, iy0], [ix0, iy1], [ox0, iy1]],
    near: [[ox0, iy1], [ix1, iy1], [ix1, oy0], [ox1, oy0], [ox1, oy1], [ox0, oy1]],
  };
}

