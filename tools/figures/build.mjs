// The single-colour mark: the tray's silhouette with its opening cut out, the print's border,
// and its photo. The three never overlap, so no boolean geometry is needed.
function markSilhouette(P, lines, m = MARK, { photo = true } = {}) {
  const plans = markPlans(m);
  const art = new Art(lines);
  const top = m.printZ + m.printH;
  art.fill(k.slabOf(plans.base, 0, m.wallTop, P, 4).fill + k.planOutline({ ...plans.inner, r: 0.8 }, m.wallTop, P, 2), "ink", { evenOdd: true });
  const gap = m.gap ?? 1.6;
  const border = k.onTop(k.ringOf(m.print, 3), top, P, true);
  const opening = k.onTop(k.ringOf(k.insetPlan(m.print, m.border - (photo ? gap : 0)), 2), top, P, true);
  art.fill(border + opening, "ink", { evenOdd: true });
  if (photo) art.fill(k.onTop(k.ringOf(k.insetPlan(m.print, m.border), 2), top, P, true), "ink");
  return art;
}

