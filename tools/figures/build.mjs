function markPlans(m) {
  const inner = { x: m.print.x - m.margin, y: m.print.y - m.margin, w: m.print.w + 2 * m.margin, d: m.print.d + 2 * m.margin };
  const tray = walls(inner, m.wall);
  const base = { ...k.insetPlan(tray.outer, -m.ledge), r: 3 };
  return { inner, outer: tray.outer, base, far: tray.far, near: tray.near };
}

const MP = markPlans(MARK);
const IP = k.fitProjection(k.boxCorners(MP.base, 0, MARK.wallTop), ICON, ICON, { pad: 23 });
// Adaptive icons are masked to as little as a 66dp circle; keep the outline strokes inside it.
const SAFE_R = 33;
const reach = Math.max(...k.boxCorners(MP.base, 0, MARK.wallTop).map((point) => Math.hypot(...k.iso(point, IP).map((v) => v - ICON / 2))));
if (reach + ICON_LINES.edge / 2 > SAFE_R) throw new Error(`icon reaches ${reach.toFixed(1)} from the centre, past the ${SAFE_R}dp safe zone`);

function markArt(P, lines, { halo = true } = {}) {
  const art = new Art(lines);
  const m = MARK;
  if (halo) haloUnder(art, MP.base, 0, P, { grow: 1.1, drop: 2.2 });
  art.solid(k.slabOf(MP.base, 0, m.baseH, P, 4, 0.6), { tone: "hi", crease: "lo" });
  art.solid(k.extrude(MP.far, m.baseH, m.wallTop - m.baseH, P, { convex: false, bevel: 0.6 }), { tone: "hi", crease: "lo" });
  art.solid(k.extrude(turned(k.ringOf(m.print, 3), m.under, [0.6, -0.8]), m.printZ - m.printH, m.printH, P), { tone: "hi", crease: "lo" });
  const top = m.printZ + m.printH;
  const photo = k.onTop(k.ringOf(k.insetPlan(m.print, m.border), 2), top, P, true);
  art.solid(k.extrude(k.ringOf(m.print, 3), m.printZ, m.printH, P), {
    tone: "hi",
    crease: "lo",
    inner: (a) => {
      a.fill(photo, "lit");
      a.stroke(photo, "litEdge", lines.line);
    },
  });
  art.solid(k.extrude(MP.near, m.baseH, m.wallTop - m.baseH, P, { convex: false, bevel: 0.6 }), { tone: "hi", crease: "lo" });
  return art;
}

// The single-colour mark: the tray's silhouette with its opening cut out, the print's border,
// and its photo. The three never overlap, so no boolean geometry is needed.
function markSilhouette(P, lines, m = MARK, { photo = true } = {}) {
  const plans = markPlans(m);
  const art = new Art(lines);
  const top = m.printZ + m.printH;
  art.fill(k.slabOf(plans.base, 0, m.wallTop, P, 4).fill + k.planOutline({ ...plans.inner, r: 0.8 }, m.wallTop, P, 2), "ink", { evenOdd: true });
  const gap = m.gap ?? 1.6;
  const border = k.onTop(k.ringOf(m.print, 3), top, P, true);
  const opening = k.onTop(k.ringOf(k.insetPlan(m.print, m.border - (photo ? gap : 0)), 2), top, P, true);
  art.fill(border + opening, "ink", { evenOdd: true });
  if (photo) art.fill(k.onTop(k.ringOf(k.insetPlan(m.print, m.border), 2), top, P, true), "ink");
  return art;
}

