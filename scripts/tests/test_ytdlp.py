import hashlib
import importlib.util
import io
import json
from pathlib import Path
import re
import shutil
import tempfile
import unittest
import zipfile

spec = importlib.util.spec_from_file_location("still_ytdlp", Path(__file__).parents[1] / "ytdlp.py")
ytdlp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ytdlp)

REPO = Path(__file__).parents[2]
BUNDLED = "2026.01.02"
NEWER = "2026.03.04"
DOWNLOAD = "https://github.com/yt-dlp/yt-dlp/releases/download/"


def zipapp(version_py):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, text in [("yt_dlp/__main__.py", ""), ("yt_dlp/version.py", version_py)]:
            archive.writestr(zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0)), text)
    return b"#!/usr/bin/env python3\n" + buffer.getvalue()


def release_zipapp(version):
    return zipapp(f"# Autogenerated by devscripts/update-version.py\n\n__version__ = '{version}'\n\nCHANNEL = 'stable'\n")


class FakeRelease:
    """Serves the GitHub API response and assets of one release, recording what was requested."""

    def __init__(self, tag, binary, sums=None, digest=True, prerelease=False, names=(ytdlp.ASSET, ytdlp.SUMS)):
        digest_hex = hashlib.sha256(binary).hexdigest()
        if sums is None:
            sums = f"{'1' * 64}  yt-dlp.exe\n{digest_hex}  yt-dlp\n{'2' * 64}  yt-dlp_linux\n"
        self.responses = {DOWNLOAD + f"{tag}/{ytdlp.ASSET}": binary, DOWNLOAD + f"{tag}/{ytdlp.SUMS}": sums.encode()}
        assets = [{"name": name, "browser_download_url": DOWNLOAD + f"{tag}/{name}"} for name in names]
        for asset in assets:
            if digest and asset["browser_download_url"] in self.responses:
                asset["digest"] = "sha256:" + hashlib.sha256(self.responses[asset["browser_download_url"]]).hexdigest()
        self.responses[ytdlp.LATEST] = json.dumps({"tag_name": tag, "draft": False, "prerelease": prerelease,
                                                   "assets": assets}).encode()
        self.requests = []

    def __call__(self, url):
        self.requests.append(url)
        return self.responses[url]


class UpdateTest(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.root)
        old = release_zipapp(BUNDLED)
        texts = ytdlp.rewrite({path: (REPO / path).read_text() for path in (ytdlp.RUNTIME, ytdlp.NOTICES)},
                              ytdlp.description(old))
        for path, content in [(ytdlp.BINARY, old), *texts.items()]:
            (self.root / path).parent.mkdir(parents=True, exist_ok=True)
            mode = "write_bytes" if isinstance(content, bytes) else "write_text"
            getattr(self.root / path, mode)(content)
        self.assertEqual(ytdlp.problems(self.root), [])

    def snapshot(self):
        return {path: (self.root / path).read_bytes() for path in (ytdlp.BINARY, ytdlp.RUNTIME, ytdlp.NOTICES)}

    def assertRefused(self, release, message):
        before = self.snapshot()
        with self.assertRaisesRegex(ValueError, message):
            ytdlp.update(self.root, release)
        self.assertEqual(self.snapshot(), before, "a refused update must not touch the checkout")

    def test_newer_release_replaces_the_binary_and_every_reference(self):
        binary = release_zipapp(NEWER)
        result = ytdlp.update(self.root, FakeRelease(NEWER, binary))
        digest = hashlib.sha256(binary).hexdigest()
        self.assertEqual(result, {"changed": True, "version": NEWER, "previous": BUNDLED, "sha256": digest,
                                  "size": len(binary)})
        self.assertEqual((self.root / ytdlp.BINARY).read_bytes(), binary)
        self.assertEqual(ytdlp.problems(self.root), [])
        runtime = (self.root / ytdlp.RUNTIME).read_text()
        notices = (self.root / ytdlp.NOTICES).read_text()
        self.assertIn(f'BUNDLED_VERSION = "{NEWER}"', runtime)
        self.assertIn(f'"{digest}"', runtime)
        self.assertIn(f"| Bundled yt-dlp {NEWER} |", notices)
        self.assertIn(f"https://github.com/yt-dlp/yt-dlp/releases/tag/{NEWER} |", notices)
        self.assertIn(f"official {NEWER} executable in `{ytdlp.BINARY}` ({len(binary):,} bytes; SHA-256 `{digest}`",
                      notices)
        self.assertNotIn(BUNDLED, runtime + notices)

    def test_only_the_bundle_lines_change(self):
        before = {path: (self.root / path).read_text().splitlines() for path in (ytdlp.RUNTIME, ytdlp.NOTICES)}
        ytdlp.update(self.root, FakeRelease(NEWER, release_zipapp(NEWER)))
        changed = sum(a != b for path, lines in before.items()
                      for a, b in zip(lines, (self.root / path).read_text().splitlines()))
        self.assertEqual(changed, 4)

    def test_current_release_is_a_no_op_that_downloads_nothing(self):
        release = FakeRelease(BUNDLED, release_zipapp(BUNDLED))
        before = self.snapshot()
        self.assertEqual(ytdlp.update(self.root, release), {"changed": False, "version": BUNDLED, "previous": BUNDLED})
        self.assertEqual(release.requests, [ytdlp.LATEST])
        self.assertEqual(self.snapshot(), before)
        result = ytdlp.update(self.root, FakeRelease(NEWER, release_zipapp(NEWER)))
        self.assertTrue(result["changed"])
        self.assertFalse(ytdlp.update(self.root, FakeRelease(NEWER, release_zipapp(NEWER)))["changed"])

    def test_a_bundle_that_disagrees_with_its_references_is_downloaded_again(self):
        binary = release_zipapp(BUNDLED)
        (self.root / ytdlp.BINARY).write_bytes(binary + b"tampered")
        self.assertTrue(ytdlp.update(self.root, FakeRelease(BUNDLED, binary))["changed"])
        self.assertEqual((self.root / ytdlp.BINARY).read_bytes(), binary)
        self.assertEqual(ytdlp.problems(self.root), [])

    def test_the_download_must_match_sha2_256sums(self):
        binary = release_zipapp(NEWER)
        self.assertRefused(FakeRelease(NEWER, binary, sums=f"{'0' * 64}  yt-dlp\n", digest=False), "SHA2-256SUMS lists")

    def test_githubs_asset_digest_must_agree_with_the_checksums(self):
        release = FakeRelease(NEWER, release_zipapp(NEWER))
        listing = json.loads(release.responses[ytdlp.LATEST])
        listing["assets"][0]["digest"] = "sha256:" + "0" * 64
        release.responses[ytdlp.LATEST] = json.dumps(listing).encode()
        self.assertRefused(release, "GitHub lists")

    def test_checksums_must_name_the_zipapp_itself(self):
        sums = f"{'1' * 64}  yt-dlp.exe\n{'2' * 64}  yt-dlp_linux\n{'3' * 64}  yt-dlp.tar.gz\n"
        self.assertRefused(FakeRelease(NEWER, release_zipapp(NEWER), sums=sums), "no checksum for yt-dlp")

    def test_the_zipapp_must_report_the_tagged_version(self):
        self.assertRefused(FakeRelease(NEWER, release_zipapp("2026.03.03")), "version.py says 2026.03.03")

    def test_only_stable_date_tagged_releases_with_both_assets_are_used(self):
        binary = release_zipapp(NEWER)
        self.assertRefused(FakeRelease(NEWER, binary, prerelease=True), "not a stable release")
        self.assertRefused(FakeRelease(NEWER + ".232323", binary), "not a YYYY.MM.DD version")
        self.assertRefused(FakeRelease(NEWER, binary, names=(ytdlp.ASSET,)), "no SHA2-256SUMS asset")
        self.assertRefused(FakeRelease(NEWER, binary, names=(ytdlp.SUMS, "yt-dlp_linux")), "no yt-dlp asset")

    def test_older_releases_are_refused(self):
        self.assertRefused(FakeRelease("2025.12.31", release_zipapp("2025.12.31")), "older than the bundled")

    def test_each_reference_must_appear_exactly_once(self):
        notices = self.root / ytdlp.NOTICES
        row = next(line for line in notices.read_text().splitlines() if line.startswith("| Bundled yt-dlp"))
        notices.write_text(notices.read_text() + row + "\n")
        self.assertRefused(FakeRelease(NEWER, release_zipapp(NEWER)), "expected one match")


class ZipappVersionTest(unittest.TestCase):
    def test_reads_the_release_version(self):
        self.assertEqual(ytdlp.zipapp_version(release_zipapp(NEWER)), NEWER)
        self.assertEqual(ytdlp.zipapp_version(zipapp(f'__version__ = "{NEWER}"\n')), NEWER)

    def test_rejects_what_extractor_runtime_could_not_read(self):
        for data, message in [(zipapp(f"__version__ = '{NEWER}.232323'\n"), "no YYYY.MM.DD"),
                              (zipapp(f"__version__ = '{NEWER}'\n" + "#" * ytdlp.VERSION_PY_LIMIT), "at most"),
                              (zipapp("RELEASE_GIT_HEAD = 'abc'\n"), "no YYYY.MM.DD"),
                              (b"#!/usr/bin/env python3\nprint()\n", "Not a yt-dlp zipapp")]:
            with self.subTest(message=message), self.assertRaisesRegex(ValueError, message):
                ytdlp.zipapp_version(data)

    def test_reader_matches_extractor_runtime(self):
        java = (REPO / ytdlp.RUNTIME).read_text()
        literal = re.search(r'Pattern\.compile\(\s*"((?:[^"\\]|\\.)*)"\)', java).group(1)
        self.assertEqual(literal.replace('\\"', '"').replace("\\\\", "\\"), ytdlp.VERSION_PY.pattern)
        self.assertIn(f"getSize() > {ytdlp.VERSION_PY_LIMIT}", java)


